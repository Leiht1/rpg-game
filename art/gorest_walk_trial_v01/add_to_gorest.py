"""Add this experimental clip to Gorest without changing app code or game assets."""
from datetime import datetime, timezone
from pathlib import Path
import hashlib
import json
import shutil

ROOT = Path(__file__).resolve().parent
GOREST = Path(r"C:\Users\HT\Documents\Codex\2026-10-15\https-github-com-0x0funky-agent-sprite\outputs\gorest-2d-animation-spritesheet-generator-main")
generated = GOREST / "public" / "generated"
library_path = generated / "game_asset_library.json"
library_bytes = library_path.read_bytes()
library = json.loads(library_bytes)
asset_id = "asset_windrest_hero_front_walk_trial_v01"
if any(a.get("id") == asset_id for a in library["assets"]):
    raise SystemExit("This trial ID already exists; refusing to replace a library entry.")

meta = json.loads((ROOT / "normalization.json").read_text(encoding="utf-8"))
qa = json.loads((ROOT / "qa.json").read_text(encoding="utf-8"))
source = ROOT / "take2" / "generated.png"
job = json.loads((ROOT / "take2" / "job.json").read_text(encoding="utf-8"))
now = datetime.now(timezone.utc).isoformat()
href = "/generated/windrest_hero_front_walk_trial_v01.png"
source_href = "/generated/sources/windrest_hero_front_walk_trial_v01/raw.png"
fps = qa["fps"]
title = f"风栖原野主角 · 正面行走试作（{meta['frameCount']}帧）"
sprite = {
    "id": "sprite_windrest_hero_front_walk_trial_v01",
    "characterName": "风栖原野主角",
    "description": "由已接受主角原图生成的正面行走完整帧试作，仅供查看；未接入游戏，未标为最终素材。",
    "frameCount": meta["frameCount"],
    "style": "warm bright hand-painted cartoon matching approved protagonist reference",
    "prompt": (ROOT / "correction_prompt.txt").read_text(encoding="utf-8"),
    "frames": meta["frames"],
    "createdTime": now,
    "isPreset": False,
    "spritesheetPng": href,
    "sourceMasterPng": source_href,
    "generationMode": "spritesheet",
    "qualityPolicy": "Experimental preview only. See source review and QA; numeric padding checks do not approve gait or anatomy.",
    "artSourcePolicy": "Whole-character bitmap poses generated by Codex (local CLI) from the approved original. Code only keys, crops, uniformly scales, registers, packs, and previews.",
    "proportionPolicy": meta["proportionPolicy"],
    "normalization": meta["normalization"],
    "rootAnchorPolicy": meta["rootAnchorPolicy"],
    "globalScale": meta["globalScale"],
    "fps": fps,
    "loop": True,
    "gridColumns": 4,
    "cellSize": meta["cellSize"],
    "frameSize": meta["frameSize"],
    "sheetSize": meta["sheetSize"],
    "sourceSheetSize": meta["sourceSheetSize"],
    "sourceCells": meta["sourceCells"],
    "sourceFrameOrder": meta["sourceFrameOrder"],
    "phaseOrderPolicy": meta["phaseOrderPolicy"],
    "gridDetection": meta["gridDetection"],
    "safePadding": meta["safePadding"],
    "safeFramePolicy": meta["safeFramePolicy"],
    "sourceEdgePolicy": meta["sourceEdgePolicy"],
    "sourceEdgeRisks": meta["sourceEdgeRisks"],
    "sourceEdgeRiskCount": len(meta["sourceEdgeRisks"]),
    "provenance": {
        "route": "local:codex-cli",
        "requestedModel": job["requestedModel"],
        "underlyingImageModel": "not exposed",
        "rawSheet": source_href,
        "rawSha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "reference": "/generated/sources/windrest_hero_front_walk_trial_v01/reference.png",
        "status": "experiment_not_game_accepted"
    }
}
binding = {"actionName": "walk", "triggerType": "auto", "triggerValue": "preview-loop",
           "gameState": "windrest.trial.front_walk", "notes": "Preview experiment only, no gameplay scene binding."}
clip_id = "clip_windrest_hero_front_walk_trial_v01"
asset = {"id": asset_id, "name": title, "role": "player", "confirmed": False,
         "savedTime": now, "updatedTime": now, "sprite": sprite,
         "animations": [{"id": clip_id, "name": title, "actionName": "walk", "direction": "down",
                         "sprite": sprite, "binding": binding, "loop": True, "fps": fps}],
         "defaultAnimationId": clip_id, "binding": binding,
         "tags": ["windrest", "hero", "front", "walk", "experiment", "not-game-integrated"]}

backup = ROOT / "gorest_library.before.json"
if backup.exists():
    raise SystemExit("Library backup already exists; refusing to overwrite it.")
backup.write_bytes(library_bytes)
source_dir = generated / "sources" / "windrest_hero_front_walk_trial_v01"
source_dir.mkdir(parents=True, exist_ok=True)
shutil.copy2(source, source_dir / "raw.png")
shutil.copy2(ROOT.parent.parent / "art" / "reference" / "hero.png", source_dir / "reference.png")
shutil.copy2(ROOT / "correction_prompt.txt", source_dir / "prompt.txt")
shutil.copy2(ROOT / "take2" / "job.json", source_dir / "job.json")
shutil.copy2(ROOT / "normalization.json", source_dir / "normalization.json")
shutil.copy2(ROOT / "qa.json", source_dir / "qa.json")
shutil.copy2(ROOT / "front_walk_sheet.png", generated / "windrest_hero_front_walk_trial_v01.png")
library["assets"].insert(0, asset)
library["updatedTime"] = now
library_path.write_text(json.dumps(library, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
(ROOT / "gorest_library_change.json").write_text(json.dumps({
    "libraryPath": str(library_path), "assetId": asset_id, "clipId": clip_id,
    "previousLibrarySha256": hashlib.sha256(library_bytes).hexdigest(),
    "currentLibrarySha256": hashlib.sha256(library_path.read_bytes()).hexdigest(),
    "existingAssetsUnchanged": json.loads(backup.read_bytes())["assets"] == library["assets"][1:],
    "sceneDataUnchanged": all(json.loads(backup.read_bytes()).get(k) == library.get(k) for k in ("scenes", "animationScenes", "startUis", "flowGraph"))
}, ensure_ascii=False, indent=2), encoding="utf-8")
print(json.dumps({"assetId": asset_id, "title": title, "frameCount": meta["frameCount"], "fps": fps}, ensure_ascii=False))
